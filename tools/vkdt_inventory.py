#!/usr/bin/env python3
"""Inventory of vkdt's processing modules, against the Helios module contract.

Reads a vkdt checkout (default ../vkdt, or $VKDT_SRC, or the first argument)
and writes docs/vkdt-inventory.json and docs/vkdt-inventory.md.

For each module under src/pipe/modules/<name>/ it records:
- params: name, type, count, defaults (the `params` file);
- connectors: name, type (read, write, source, sink, modify), channels,
  format, and flags such as feedback (the `connectors` file);
- widgets: the widget type of each parameter (the `params.ui` file);
- code: which callbacks main.c defines, and how many compute shaders;
- category: from the module list in src/pipe/modules/readme.md.

Detection reads the files as data; it never builds or runs vkdt.
"""

import json
import os
import re
import sys
from pathlib import Path

CALLBACKS = [
    "create_nodes",
    "modify_roi_in",
    "modify_roi_out",
    "commit_params",
    "check_params",
    "read_source",
    "write_sink",
    "animate",
    "init",
    "cleanup",
    "ui_callback",
    "audio",
    "input",
]


def read_lines(path):
    if not path.exists():
        return []
    return [
        line.strip()
        for line in path.read_text(errors="replace").splitlines()
        if line.strip() and not line.startswith("#")
    ]


def parse_params(path):
    params = []
    for line in read_lines(path):
        parts = line.split(":")
        if len(parts) < 3:
            continue
        name, kind, count = parts[0], parts[1], parts[2]
        params.append({"name": name, "type": kind, "count": count, "default": parts[3:]})
    return params


def parse_connectors(path):
    connectors = []
    for line in read_lines(path):
        parts = line.split(":")
        if len(parts) < 4:
            continue
        connectors.append(
            {
                "name": parts[0],
                "type": parts[1],
                "channels": parts[2],
                "format": parts[3],
                "flags": parts[4:],
            }
        )
    return connectors


def parse_widgets(path):
    widgets = {}
    for line in read_lines(path):
        parts = line.split(":")
        if len(parts) >= 2 and parts[0] not in ("group", "---"):
            widgets[parts[0]] = parts[1]
    return widgets


def callbacks(main_c):
    if not main_c.exists():
        return []
    text = main_c.read_text(errors="replace")
    return [c for c in CALLBACKS if re.search(r"^\s*(?:[\w\s\*]+?)\b" + c + r"\s*\(", text, re.M)]


def categories(readme):
    found, current = {}, None
    for line in readme.read_text(errors="replace").splitlines() if readme.exists() else []:
        m = re.match(r"^\*\*(.+)\*\*\s*$", line.strip())
        if m:
            current = m.group(1)
            continue
        m = re.match(r"^\*\s*\[([\w\-]+):", line.strip())
        if m and current:
            found[m.group(1)] = current
    return found


def inventory(src):
    root = src / "src" / "pipe" / "modules"
    cats = categories(root / "readme.md")
    modules = []
    for d in sorted(p for p in root.iterdir() if p.is_dir()):
        if not (d / "connectors").exists() and not (d / "params").exists():
            continue
        connectors = parse_connectors(d / "connectors")
        modules.append(
            {
                "name": d.name,
                "category": cats.get(d.name, "unlisted"),
                "params": parse_params(d / "params"),
                "connectors": connectors,
                "widgets": parse_widgets(d / "params.ui"),
                "callbacks": callbacks(d / "main.c"),
                "shaders": len(list(d.glob("*.comp"))),
                "inputs": sum(c["type"] in ("read", "sink", "modify") for c in connectors),
                "outputs": sum(c["type"] in ("write", "source") for c in connectors),
                # Feedback (between frames) is wired by the module's code, not its files.
                "feedback": (d / "main.c").exists()
                and "dt_node_feedback" in (d / "main.c").read_text(errors="replace"),
            }
        )
    return modules


def markdown(modules, revision):
    count = len(modules)

    def share(pred):
        n = sum(1 for m in modules if pred(m))
        return f"{n} / {count}"

    lines = [
        "# vkdt module inventory (helios)",
        "",
        "Generated by `tools/vkdt_inventory.py` from a vkdt checkout"
        + (f" at {revision}" if revision else "")
        + ". Do not edit by hand. Detection reads module files as data: see the JSON for details.",
        "",
        f"- Modules: **{count}**",
        f"- With parameters: {share(lambda m: m['params'])}; parameters in all: {sum(len(m['params']) for m in modules)}",
        f"- Several nodes (`create_nodes`): {share(lambda m: 'create_nodes' in m['callbacks'])}",
        f"- Change the region (`modify_roi_*`): {share(lambda m: 'modify_roi_in' in m['callbacks'] or 'modify_roi_out' in m['callbacks'])}",
        f"- Translate parameters before use (`commit_params`): {share(lambda m: 'commit_params' in m['callbacks'])}",
        f"- Sources (`read_source`): {share(lambda m: 'read_source' in m['callbacks'])}; sinks (`write_sink`): {share(lambda m: 'write_sink' in m['callbacks'])}",
        f"- Animated (`animate`): {share(lambda m: 'animate' in m['callbacks'])}",
        f"- Several inputs: {share(lambda m: m['inputs'] > 1)}; several outputs: {share(lambda m: m['outputs'] > 1)}",
        f"- Feedback connectors (between frames): {share(lambda m: m['feedback'])}",
        f"- No module code (one shader, files only): {share(lambda m: not m['callbacks'])}",
        "",
        "## By module",
        "",
        "| module | category | params | in | out | shaders | callbacks |",
        "|---|---|---|---|---|---|---|",
    ]
    for m in modules:
        lines.append(
            f"| {m['name']} | {m['category']} | {len(m['params'])} | {m['inputs']} | {m['outputs']} | {m['shaders']} | {', '.join(m['callbacks'])} |"
        )
    return "\n".join(lines) + "\n"


def main():
    src = Path(
        sys.argv[1] if len(sys.argv) > 1 else os.environ.get("VKDT_SRC", "../vkdt")
    ).resolve()
    if not (src / "src" / "pipe" / "modules").exists():
        sys.exit(f"vkdt_inventory: no vkdt checkout at {src} (pass its path or set VKDT_SRC)")
    head = src / ".git" / "HEAD"
    revision = ""
    if head.exists():
        ref = head.read_text().strip()
        if ref.startswith("ref: "):
            ref_file = src / ".git" / ref[5:]
            revision = ref_file.read_text().strip()[:9] if ref_file.exists() else ""
        else:
            revision = ref[:9]
    modules = inventory(src)
    docs = Path(__file__).resolve().parent.parent / "docs"
    (docs / "vkdt-inventory.json").write_text(
        json.dumps({"revision": revision, "modules": modules}, indent=1) + "\n"
    )
    (docs / "vkdt-inventory.md").write_text(markdown(modules, revision))
    print(f"{len(modules)} modules")


if __name__ == "__main__":
    main()
