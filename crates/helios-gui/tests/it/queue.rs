const LONG: Duration = Duration::from_secs(20);

const FAST: Timing = Timing {
    retry: Duration::from_millis(20),
    forget_after: Duration::from_mins(10),
    silence: Duration::from_secs(5),
};

/// Far ahead, in milliseconds: the rows' waits read `0 s` in the picture.
const AHEAD_MS: u64 = 4_102_444_800_000;

fn harness(when_empty: bool) -> Harness<'static, Shell> {
    let mut shell = Shell::new(helios_panels(), None);
    shell.set_queue_when_empty(when_empty);
    let mut h = headless::harness(shell, vec2(1280.0, 800.0));
    h.run_steps(4);
    h
}

/// Selects a node of the graph, as the graph editor does.
fn select(h: &mut Harness<'_, Shell>, node: &str) {
    h.state()
        .values()
        .lock()
        .unwrap()
        .set(Set::new(
            helios_gui::params::SELECTION,
            Change::To(Value::Text(node.into())),
            Origin::User,
        ))
        .unwrap();
    h.run_steps(4);
}

/// Brings the Queue panel to the front of its area.
fn show_queue(h: &mut Harness<'_, Shell>) {
    h.state_mut()
        .run("helios.queue.focus", json!(null), Origin::User)
        .unwrap();
    h.run_steps(4);
}

fn visible(h: &Harness<'_, Shell>) -> bool {
    h.state()
        .app()
        .handle()
        .panel_visible(&PanelId::new(PANEL).unwrap())
}

/// The titles and states of the followed node's items.
fn items(h: &Harness<'_, Shell>) -> Vec<(String, ItemState)> {
    h.state()
        .queue_panel()
        .queue()
        .map(|q| q.items.iter().map(|i| (i.title.clone(), i.state)).collect())
        .unwrap_or_default()
}

/// Runs frames until `done`, or fails after [`LONG`].
fn until(h: &mut Harness<'_, Shell>, what: &str, done: impl Fn(&Harness<'_, Shell>) -> bool) {
    let deadline = Instant::now() + LONG;
    loop {
        h.run_steps(4);
        if done(h) {
            return;
        }
        assert!(Instant::now() < deadline, "{what}: {:?}", items(h));
        std::thread::sleep(Duration::from_millis(20));
    }
}

/// A job's promise, as the node mirrors it.
fn promise(id: &str, job: &str, label: &str, state: State) -> Promise {
    Promise {
        id: id.into(),
        owner: job.into(),
        kind: "export".into(),
        label: label.into(),
        request: json!({ "job": job, "cancellable": true }),
        state,
        cancel_asked: false,
        attempts: 1,
        paused: None,
        created: 1_794_650_000,
        updated: 1_794_650_000,
    }
}

fn running() -> State {
    State::Running {
        done: 0,
        total: Some(1),
        note: None,
    }
}

// --- A node running a workflow run --------------------------------------

/// One item of the run, as the node keeps it.
#[derive(Clone)]
struct Item {
    id: String,
    status: &'static str,
    attempts: u32,
    error: Option<&'static str>,
}

/// A node's workflow level, reduced to what the panel reads and asks: one
/// run queueing at `export`, its items in claim order. Each verb changes
/// the rows and says it on the node's bus, as `helios-node` does.
struct Runs {
    items: Vec<Item>,
    asked: Vec<ControlRequest>,
}

fn row(item: &Item) -> serde_json::Value {
    json!({
        "item": item.id,
        "status": item.status,
        "attempts": item.attempts,
        "since": AHEAD_MS,
        "error": item.error,
    })
}

struct Node {
    dir: PathBuf,
    bus: Arc<Bus>,
    runs: Arc<Mutex<Runs>>,
}

impl Node {
    fn start(name: &str) -> Node {
        let dir = std::env::temp_dir().join(format!("helios-queue-{name}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        let bus = Arc::new(Bus::with_journal(helios_core::bus::JOURNAL));
        let inspector = Inspector::new(bus.clone()).with_jobs();
        helios_inspect::serve(inspector, &dir.join("node.sock")).unwrap();
        let item = |name: &str, status, attempts, error| Item {
            id: format!("path:/photos/{name}"),
            status,
            attempts,
            error,
        };
        let runs = Arc::new(Mutex::new(Runs {
            items: vec![
                item("a.jpg", "failed", 3, Some("cannot read the file")),
                item("b.jpg", "waiting", 0, None),
                item("c.jpg", "waiting", 0, None),
            ],
            asked: Vec::new(),
        }));
        let (served, said) = (runs.clone(), bus.clone());
        helios_inspect::serve_at(
            &Listen::Unix(dir.join("control.sock")),
            None,
            move |request: ControlRequest| answer(&served, &said, request),
        )
        .unwrap();
        Node { dir, bus, runs }
    }

    fn link(&self, name: &str) -> NodeLink {
        NodeLink {
            name: name.into(),
            inspect: Address::Unix(self.dir.join("node.sock")),
            control: Some(Address::Unix(self.dir.join("control.sock"))),
        }
    }

    /// The verbs asked, the reads left out.
    fn verbs(&self) -> Vec<ControlRequest> {
        self.runs
            .lock()
            .unwrap()
            .asked
            .iter()
            .filter(|r| {
                !matches!(
                    r,
                    ControlRequest::WorkflowRuns | ControlRequest::WorkflowItems { .. }
                )
            })
            .cloned()
            .collect()
    }
}

impl Drop for Node {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.dir);
    }
}

/// The node's answer to `request`, its rows changed and said.
fn answer(runs: &Mutex<Runs>, bus: &Bus, request: ControlRequest) -> serde_json::Value {
    let mut runs = runs.lock().unwrap();
    let say_rows = |runs: &Runs, which: &[String]| {
        let items: Vec<_> = runs
            .items
            .iter()
            .filter(|i| which.contains(&i.id))
            .map(row)
            .collect();
        bus.publish_value(
            "workflow",
            None,
            "helios.workflow.rows",
            json!({ "run": "run-1", "node": "export", "items": items }),
        );
    };
    let out = match &request {
        ControlRequest::WorkflowRuns => json!({ "ok": true, "now": 0, "runs": [{
            "id": "run-1", "title": "Export 3 photos", "state": "running",
            "read_only": false, "created": AHEAD_MS, "items": runs.items.len(),
            "nodes": { "export": { "queue": "export" } },
        }]}),
        ControlRequest::WorkflowItems { .. } => {
            let items: Vec<_> = runs
                .items
                .iter()
                .map(|i| {
                    json!({
                        "item": i.id,
                        "title": i.id.rsplit('/').next(),
                        "state": i.status,
                        "row": (i.status != "waiting").then(|| row(i)),
                        "error": i.error,
                    })
                })
                .collect();
            json!({ "ok": true, "run": "run-1", "node": "export", "total": items.len(),
                    "offset": 0, "items": items, "now": 0 })
        }
        ControlRequest::WorkflowRetry {
            items: Some(which), ..
        } => {
            for i in runs.items.iter_mut().filter(|i| which.contains(&i.id)) {
                (i.status, i.error) = ("scheduled", None);
            }
            say_rows(&runs, which);
            json!({ "ok": true, "run": "run-1", "retried": which.len() })
        }
        ControlRequest::WorkflowCancel {
            items: Some(which), ..
        } => {
            for i in runs.items.iter_mut().filter(|i| which.contains(&i.id)) {
                i.status = "cancelled";
            }
            say_rows(&runs, which);
            json!({ "ok": true, "run": "run-1", "cancelled": which.len() })
        }
        ControlRequest::WorkflowPrioritize {
            items: which, to, ..
        } => {
            let (moved, rest): (Vec<Item>, Vec<Item>) =
                runs.items.drain(..).partition(|i| which.contains(&i.id));
            runs.items = match to {
                MoveTo::Top => moved.into_iter().chain(rest).collect(),
                MoveTo::Bottom => rest.into_iter().chain(moved).collect(),
            };
            bus.publish_value(
                "workflow",
                None,
                "helios.workflow.run",
                json!({ "run": "run-1", "title": "Export 3 photos", "state": "reordered",
                        "items": which, "to": to }),
            );
            json!({ "ok": true, "run": "run-1" })
        }
        _ => json!({ "ok": false, "error": "not served here" }),
    };
    runs.asked.push(request);
    out
}

fn following(node: &Node) -> Harness<'static, Shell> {
    let mut h = harness(true);
    h.state_mut()
        .follow_node_with(node.link("box"), FAST)
        .unwrap();
    select(&mut h, "export");
    show_queue(&mut h);
    until(&mut h, "the run's rows", |h| items(h).len() == 3);
    h
}

#[test]
fn a_run_s_rows_at_the_node_are_its_queue() {
    let node = Node::start("rows");
    let mut h = following(&node);
    assert_eq!(
        items(&h),
        [
            ("a.jpg".to_string(), ItemState::Failed),
            ("b.jpg".to_string(), ItemState::Waiting),
            ("c.jpg".to_string(), ItemState::Waiting),
        ]
    );
    {
        let panel = h.state().queue_panel();
        let queue = panel.queue().unwrap();
        assert!(
            queue
                .items
                .iter()
                .all(|i| i.place == Place::Node("box".into()))
        );
        assert_eq!(queue.items[0].attempts, 3);
        assert_eq!(
            queue.items[0].error.as_deref(),
            Some("cannot read the file")
        );
        assert_eq!(queue.items[0].actions, [Action::Retry]);
        assert_eq!(
            queue.items[1].actions,
            [Action::Top, Action::Bottom, Action::Cancel]
        );
    }
    h.get_by_label("Queue of export");
    h.get_by_label("2 waiting, 0 running, 0 done, 1 failed");

    // A row the node says changed: the panel follows the fact.
    node.bus.publish_value(
        "workflow",
        None,
        "helios.workflow.rows",
        json!({ "run": "run-1", "node": "export", "items": [{
            "item": "path:/photos/b.jpg", "status": "running", "attempts": 1,
            "since": AHEAD_MS, "due": null, "error": null,
        }]}),
    );
    until(&mut h, "b.jpg running", |h| {
        items(h).get(1) == Some(&("b.jpg".to_string(), ItemState::Running))
    });

    // Another node of the graph has no queue.
    select(&mut h, "grade");
    assert!(h.state().queue_panel().is_empty());
}

#[test]
fn retry_move_and_cancel_reach_the_node_and_the_rows_follow() {
    let node = Node::start("verbs");
    let mut h = following(&node);

    h.get_by_label("Retry a.jpg").click();
    until(&mut h, "a.jpg retried", |h| {
        items(h)[0] == ("a.jpg".to_string(), ItemState::Waiting)
    });

    // The panel shows the first rows; the ones below scroll.
    h.get_by_label("Top b.jpg").click();
    until(&mut h, "Move asked", |_| node.verbs().len() == 2);
    until(&mut h, "b.jpg first", |h| items(h)[0].0 == "b.jpg");

    h.get_by_label("Cancel b.jpg").click();
    until(&mut h, "b.jpg cancelled", |h| {
        items(h)[0] == ("b.jpg".to_string(), ItemState::Cancelled)
    });
    assert_eq!(
        items(&h),
        [
            ("b.jpg".to_string(), ItemState::Cancelled),
            ("a.jpg".to_string(), ItemState::Waiting),
            ("c.jpg".to_string(), ItemState::Waiting),
        ]
    );

    let one = |name: &str| vec![format!("path:/photos/{name}")];
    assert_eq!(
        node.verbs(),
        [
            ControlRequest::WorkflowRetry {
                run: "run-1".into(),
                items: Some(one("a.jpg")),
                node: None,
            },
            ControlRequest::WorkflowPrioritize {
                run: "run-1".into(),
                items: one("b.jpg"),
                to: MoveTo::Top,
            },
            ControlRequest::WorkflowCancel {
                run: "run-1".into(),
                items: Some(one("b.jpg")),
                node: None,
            },
        ]
    );
}

/// The same verbs, run as an agent would: the bus command, not the panel.
#[test]
fn an_agent_runs_the_same_verbs() {
    let node = Node::start("agent");
    let mut h = following(&node);
    h.state_mut()
        .run(
            "helios.workflow.retry",
            json!({ "node": "box", "run": "run-1", "items": ["path:/photos/a.jpg"] }),
            Origin::Agent("helper".into()),
        )
        .unwrap();
    until(&mut h, "a.jpg retried", |h| {
        items(h)[0] == ("a.jpg".to_string(), ItemState::Waiting)
    });
    assert_eq!(node.verbs().len(), 1);
}

